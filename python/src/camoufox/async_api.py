async def AsyncNewBrowser(
    playwright: Playwright,
    *,
    headless: Optional[Union[bool, Literal['virtual', 'virtual-gpu']]] = None,
    from_options: Optional[Dict[str, Any]] = None,
    persistent_context: bool = False,
    debug: Optional[bool] = None,
    **kwargs,
) -> Union[Browser, BrowserContext]:
    """
    Launches a new browser instance for Camoufox given a set of launch options.

    Parameters:
        headless (Optional[Union[bool, Literal['virtual', 'virtual-gpu']]]):
            True for Firefox headless. On Linux, 'virtual' runs a headed browser on
            an Xvfb display, and 'virtual-gpu' on a headless Xorg server bound to
            the GPU `gpu` (or CAMOUFOX_GPU) names; `require_gpu=False` warns instead
            of failing when the browser does not render on it.
        from_options (Dict[str, Any]):
            A set of launch options generated by `launch_options()` to use
        persistent_context (bool):
            Whether to use a persistent context.
        **kwargs:
            All other keyword arguments passed to `launch_options()`.
    """
    virtual_display, headless = await asyncio.get_running_loop().run_in_executor(
        None, start_virtual_display, headless, debug, kwargs
    )
    # Everything after the display exists can fail (bad proxy, missing binary,
    # unsatisfiable constraints) before sync/async_attach_vd wires kill() into
    # close, which used to strand one Xvfb and its /tmp/.X<n> lock per failed
    # launch.
    try:
        return await _new_browser(
            playwright, virtual_display, headless, from_options, persistent_context, debug, kwargs
        )
    except BaseException:
        if virtual_display:
            virtual_display.kill()
        raise


async def _new_browser(
    playwright: Playwright,
    virtual_display: Optional[VirtualDisplay],
    headless: Any,
    from_options: Optional[Dict[str, Any]],
    persistent_context: bool,
    debug: Optional[bool],
    kwargs: Dict[str, Any],
) -> Union[Browser, BrowserContext]:
    # Options the caller built leave its contexts to the caller (host_identity).
    canvas_noise: Optional[bool] = False
    if not from_options:
        canvas_noise = kwargs.get('canvas_noise')
        # Opt-in; see the note in sync_api.NewBrowser.
        kwargs.setdefault('pin_cpu_cores', False)
        from_options = await asyncio.get_event_loop().run_in_executor(
            None,
            partial(launch_options, headless=headless, debug=debug, **kwargs),
        )
    from_options = with_first_launch_timeout(from_options)

    # Playwright's default viewport deadlocks Juggler when the window is spoofed
    # to a different size (daijro/camoufox#666), so default to no_viewport.
    no_viewport_default = spoofs_window_dimensions(from_options)

    # Pin the driver (and so the browser it is about to spawn) to as many
    # cores as the identity reports, so measurable parallelism matches
    # navigator.hardwareConcurrency; the driver gets its cores back afterwards.
    from . import cpu_affinity
    from .utils import driver_pid, pinned_core_count

    pin_to = pinned_core_count(from_options)
    pid = driver_pid(playwright) if pin_to else None
    if not pid:
        return await _launch(
            playwright, from_options, persistent_context, no_viewport_default, virtual_display, canvas_noise
        )
    # The browser inherits the driver's mask at spawn, so two concurrent launches
    # on one driver must not interleave pin/restore: the second pin would land on
    # the first browser, and the first restore would leave the driver pinned.
    async with _pin_lock(pid):
        previous = cpu_affinity.pin(pid, pin_to)
        try:
            return await _launch(
                playwright, from_options, persistent_context, no_viewport_default, virtual_display, canvas_noise
            )
        finally:
            cpu_affinity.restore(pid, previous)


_PIN_LOCKS: Dict[int, asyncio.Lock] = {}


def _pin_lock(pid: int) -> asyncio.Lock:
    # One lock per driver: a driver belongs to one event loop.
    lock = _PIN_LOCKS.get(pid)
    if lock is None:
        lock = _PIN_LOCKS[pid] = asyncio.Lock()
    return lock


async def _launch(
    playwright: Playwright,
    from_options: Dict[str, Any],
    persistent_context: bool,
    no_viewport_default: bool,
    virtual_display: Optional[VirtualDisplay],
    canvas_noise: Optional[bool],
) -> Union[Browser, BrowserContext]:
    if persistent_context:
        context = await playwright.firefox.launch_persistent_context(
            **persistent_context_options(from_options, no_viewport_default)
        )
        return await async_attach_vd(context, virtual_display)

    identity = await asyncio.get_running_loop().run_in_executor(None, host_identity, from_options, canvas_noise)
    browser = await playwright.firefox.launch(**from_options)
    attach_context_defaults(browser, no_viewport_default, launches_mobile(from_options))
    browser._camoufox_host_identity = identity
    browser._camoufox_machine = launch_machine(from_options)
    return await async_attach_vd(browser, virtual_display)


async def _resolve_proxy_geo(proxy: Dict[str, str]) -> ExitGeo:
    """Where the proxy exits, looked up off the event loop."""
    # run_in_executor rather than asyncio.to_thread, which needs Python 3.9.
    loop = asyncio.get_running_loop()
    return await loop.run_in_executor(None, proxy_exit_geo, Proxy(**proxy).as_string())


async def async_browser_machine(browser: Browser) -> Tuple[HostIdentity, Dict[str, Any]]:
    """browser_machine() for the async API. Contexts opened at once share one probe."""
    if '_camoufox_machine' not in vars(browser):
        if '_camoufox_probe' not in vars(browser):
            async def probe_once() -> None:
                probe = await browser.new_context()
                try:
                    facts = await (await probe.new_page()).evaluate(MACHINE_PROBE)
                finally:
                    await probe.close()
                browser._camoufox_host_identity, browser._camoufox_machine = machine_from_probe(facts)

            browser._camoufox_probe = asyncio.ensure_future(probe_once())
        task = browser._camoufox_probe
        try:
            await asyncio.shield(task)
        finally:
            # A failed probe is asked again by the next context.
            if task.done():
                vars(browser).pop('_camoufox_probe', None)
    return vars(browser).get('_camoufox_host_identity'), browser._camoufox_machine


async def AsyncNewIdentity(
    browser: Browser,
    identity: Optional[Dict[str, Any]] = None,
    *,
    preset: Optional[Dict[str, Any]] = None,
    os: Optional[str] = None,
    ff_version: Optional[str] = None,
    locale: Optional[str] = None,
    timezone: Optional[str] = None,
    webrtc_ip: Optional[str] = None,
    proxy: Optional[Dict[str, str]] = None,
    geolocation: Optional[Dict[str, float]] = None,
    overrides: Optional[Dict[str, Any]] = None,
    i_know_what_im_doing: bool = False,
) -> Dict[str, Any]:
    """The async NewIdentity (camoufox.sync_api.NewIdentity has the parameters)."""
    ff_version = ff_version or browser.version.split('.', 1)[0]
    host_identity, machine = await async_browser_machine(browser)
    if proxy and needs_exit_geo(identity, webrtc_ip, geolocation, timezone, locale):
        webrtc_ip, geolocation, timezone, locale = place_at_exit(
            await _resolve_proxy_geo(proxy), identity, webrtc_ip, geolocation, timezone, locale
        )
    return await asyncio.get_running_loop().run_in_executor(None, partial(
        context_identity, host_identity, machine, identity, ff_version, preset=preset, os=os,
        locale=locale, timezone=timezone, webrtc_ip=webrtc_ip, geolocation=geolocation,
        overrides=overrides, i_know_what_im_doing=i_know_what_im_doing,
    ))


async def AsyncNewContext(
    browser: Browser,
    identity: Optional[Dict[str, Any]] = None,
    *,
    preset: Optional[Dict[str, Any]] = None,
    os: Optional[str] = None,
    ff_version: Optional[str] = None,
    webrtc_ip: Optional[str] = None,
    proxy: Optional[Dict[str, str]] = None,
    geolocation: Optional[Dict[str, float]] = None,
    overrides: Optional[Dict[str, Any]] = None,
    i_know_what_im_doing: bool = False,
    **context_kwargs: Any,
) -> BrowserContext:
    """The async NewContext (camoufox.sync_api.NewContext has the parameters)."""
    ff_version = ff_version or browser.version.split('.', 1)[0]
    drawn = await AsyncNewIdentity(
        browser, identity, preset=preset, os=os, ff_version=ff_version,
        locale=context_kwargs.pop('locale', None), timezone=context_kwargs.pop('timezone_id', None),
        webrtc_ip=webrtc_ip, proxy=proxy, geolocation=geolocation, overrides=overrides,
        i_know_what_im_doing=i_know_what_im_doing,
    )
    rendered = render_context_identity(drawn, ff_version, i_know_what_im_doing)
    context = await browser.new_context(**new_context_options(rendered, context_kwargs, proxy))
    await context.add_init_script(rendered['init_script'])
    context.camoufox_identity = drawn
    return context
