def NewBrowser(
    playwright: Playwright,
    *,
    headless: Optional[Union[bool, Literal['virtual', 'virtual-gpu']]] = None,
    from_options: Optional[Dict[str, Any]] = None,
    persistent_context: bool = False,
    debug: Optional[bool] = None,
    **kwargs,
) -> Union[Browser, BrowserContext]:
    """
    Launches a new browser instance for Camoufox given a set of launch options.

    Parameters:
        headless (Optional[Union[bool, Literal['virtual', 'virtual-gpu']]]):
            True for Firefox headless. On Linux, 'virtual' runs a headed browser on
            an Xvfb display, and 'virtual-gpu' on a headless Xorg server bound to
            the GPU `gpu` (or CAMOUFOX_GPU) names; `require_gpu=False` warns instead
            of failing when the browser does not render on it.
        from_options (Dict[str, Any]):
            A set of launch options generated by `launch_options()` to use
        persistent_context (bool):
            Whether to use a persistent context.
        **kwargs:
            All other keyword arguments passed to `launch_options()`.
    """
    # humanize runs in this process: checked before the launch,
    # attached to the browser after it (also with from_options).
    _humanize_playwright.check(kwargs.get('humanize'), is_async=False)
    virtual_display, headless = start_virtual_display(headless, debug, kwargs)
    # Everything after the display exists can fail (bad proxy, missing binary,
    # unsatisfiable constraints) before sync/async_attach_vd wires kill() into
    # close, which used to strand one Xvfb and its /tmp/.X<n> lock per failed
    # launch.
    try:
        browser, os = _launch(playwright, virtual_display, headless, from_options, persistent_context, debug, kwargs)
        return _humanize_playwright.attach(
            browser, kwargs.get('humanize'), os, i_know_what_im_doing=kwargs.get('i_know_what_im_doing')
        )
    except BaseException:
        if virtual_display:
            virtual_display.kill()
        raise


def _launch(
    playwright: Playwright,
    virtual_display: Optional[VirtualDisplay],
    headless: Any,
    from_options: Optional[Dict[str, Any]],
    persistent_context: bool,
    debug: Optional[bool],
    kwargs: Dict[str, Any],
) -> Tuple[Union[Browser, BrowserContext], str]:
    """The browser (or persistent context), and its identity's OS."""
    # Options the caller built leave its contexts to the caller (host_identity).
    canvas_noise: Optional[bool] = False
    if not from_options:
        canvas_noise = kwargs.get('canvas_noise')
        # Opt-in (2026-09-17). Pinning keeps the identity's core count by
        # constraining the browser to that many cores; it costs real CPU, needs
        # a launch lock, and does nothing on macOS. What it defends against is a
        # page timing N parallel workers, which is expensive and noisy on a busy
        # machine. Off, the host's own snapped count is reported, so reported
        # and measurable still agree -- the identity just loses that one draw.
        kwargs.setdefault('pin_cpu_cores', False)
        from_options = launch_options(headless=headless, debug=debug, **kwargs)
    from_options = with_first_launch_timeout(from_options)

    # Playwright's default viewport deadlocks Juggler when the window is spoofed
    # to a different size (daijro/camoufox#666), so default to no_viewport.
    no_viewport_default = spoofs_window_dimensions(from_options)

    # Pin the driver (and so the browser it is about to spawn) to as many
    # cores as the identity reports, so measurable parallelism matches
    # navigator.hardwareConcurrency; the driver gets its cores back afterwards.
    from . import cpu_affinity
    from .utils import driver_pid, pinned_core_count

    pin_to = pinned_core_count(from_options)
    pid = driver_pid(playwright) if pin_to else None
    previous = cpu_affinity.pin(pid, pin_to) if pid else None
    try:
        if persistent_context:
            context = playwright.firefox.launch_persistent_context(
                **persistent_context_options(from_options, no_viewport_default)
            )
            driver_defaults.mark(context)
            return sync_attach_vd(context, virtual_display), launch_os(from_options)

        identity = host_identity(from_options, canvas_noise)
        browser = playwright.firefox.launch(**from_options)
        attach_context_defaults(browser, no_viewport_default, launches_mobile(from_options))
        browser._camoufox_host_identity = identity
        browser._camoufox_machine = launch_machine(from_options)
        return sync_attach_vd(browser, virtual_display), launch_os(from_options)
    finally:
        if pid:
            cpu_affinity.restore(pid, previous)


def _resolve_proxy_geo(proxy: Dict[str, str]) -> ExitGeo:
    """Where the proxy exits."""
    return proxy_exit_geo(Proxy(**proxy).as_string())


def browser_machine(browser: Browser) -> Tuple[HostIdentity, Dict[str, Any]]:
    """The host identity and machine a browser's contexts must keep. A browser
    from NewBrowser knows them; one from firefox.connect() is asked once."""
    if '_camoufox_machine' not in vars(browser):
        probe = browser.new_context()
        try:
            facts = probe.new_page().evaluate(MACHINE_PROBE)
        finally:
            probe.close()
        browser._camoufox_host_identity, browser._camoufox_machine = machine_from_probe(facts)
    return vars(browser).get('_camoufox_host_identity'), browser._camoufox_machine


def NewIdentity(
    browser: Browser,
    identity: Optional[Dict[str, Any]] = None,
    *,
    preset: Optional[Dict[str, Any]] = None,
    os: Optional[str] = None,
    ff_version: Optional[str] = None,
    locale: Optional[str] = None,
    timezone: Optional[str] = None,
    webrtc_ip: Optional[str] = None,
    proxy: Optional[Dict[str, str]] = None,
    geolocation: Optional[Dict[str, float]] = None,
    overrides: Optional[Dict[str, Any]] = None,
    i_know_what_im_doing: bool = False,
) -> Dict[str, Any]:
    """
    Draws a context identity for `browser`, or changes a stored one, without
    opening a context. The result is plain JSON: store it, and pass it to
    NewContext(identity=...) to open a context that is that identity.

    Parameters:
        identity: A stored identity to start from. Its values are kept, except
            the ones this call sets and what is drawn from them (see overrides).
        preset: A fingerprint preset dict to draw from. If None, fpgen draws.
        os: Target OS for a drawn identity ("windows", "macos", "linux", "android"). On a browser
            launched without canvas noise, contexts claim the host's OS and GPU, and another OS or
            GPU raises ValueError; "android" draws from the Linux pools, so a Linux host can render it.
        ff_version: Firefox major version to claim in the UA. Defaults to the browser's own.
        locale: BCP-47 tag or language list (Playwright's `locale`).
        timezone: IANA timezone.
        webrtc_ip: IPv4 or IPv6 address WebRTC reports.
        proxy: Only read to place the identity where the proxy exits: the WebRTC IP, timezone and
            geolocation follow the exit, and a new identity's locale is drawn for its country,
            unless given. InvalidIP is raised if that lookup fails. It is not stored.
        geolocation: {"latitude": float, "longitude": float[, "accuracy": float]}.
        overrides: Config keys to set (camoufox.fingerprints.CONTEXT_IDENTITY_KEYS, and the
            webGl: and webGl2: keys). The rest of the identity is drawn to agree: another user
            agent, platform or screen draws the fonts, voices and GPU again, from the identity's
            own salt, and another GPU brings its own WebGL tables. A key every context of a
            browser shares raises ValueError.
        i_know_what_im_doing: Silences the warnings for overrides and for phone identities.
    """
    ff_version = ff_version or browser.version.split('.', 1)[0]
    host_identity, machine = browser_machine(browser)
    if proxy and needs_exit_geo(identity, webrtc_ip, geolocation, timezone, locale):
        webrtc_ip, geolocation, timezone, locale = place_at_exit(
            _resolve_proxy_geo(proxy), identity, webrtc_ip, geolocation, timezone, locale
        )
    return context_identity(
        host_identity, machine, identity, ff_version, preset=preset, os=os, locale=locale,
        timezone=timezone, webrtc_ip=webrtc_ip, geolocation=geolocation, overrides=overrides,
        i_know_what_im_doing=i_know_what_im_doing,
    )


def NewContext(
    browser: Browser,
    identity: Optional[Dict[str, Any]] = None,
    *,
    preset: Optional[Dict[str, Any]] = None,
    os: Optional[str] = None,
    ff_version: Optional[str] = None,
    webrtc_ip: Optional[str] = None,
    proxy: Optional[Dict[str, str]] = None,
    geolocation: Optional[Dict[str, float]] = None,
    overrides: Optional[Dict[str, Any]] = None,
    i_know_what_im_doing: bool = False,
    **context_kwargs: Any,
) -> BrowserContext:
    """
    Creates a new browser context with its own identity: a new one, drawn as a
    launch draws one, or the stored `identity` (from NewIdentity, or an earlier
    context's `camoufox_identity`). The identity's values are applied through
    addInitScript, whose setters remove themselves before page scripts run, and
    the context's `camoufox_identity` holds it, to store and replay.

    `locale` and `timezone_id` in context_kwargs are part of the identity. The
    other parameters are NewIdentity's; `proxy` is also the context's proxy
    (Playwright format: {"server": "...", "username": "...", "password": "..."}).
    **context_kwargs are passed to Playwright's new_context(), and win over
    the identity's options: pass storage_state to restore a returning
    visitor's cookies and storage, and save them with context.storage_state().
    """
    ff_version = ff_version or browser.version.split('.', 1)[0]
    drawn = NewIdentity(
        browser, identity, preset=preset, os=os, ff_version=ff_version,
        locale=context_kwargs.pop('locale', None), timezone=context_kwargs.pop('timezone_id', None),
        webrtc_ip=webrtc_ip, proxy=proxy, geolocation=geolocation, overrides=overrides,
        i_know_what_im_doing=i_know_what_im_doing,
    )
    rendered = render_context_identity(drawn, ff_version, i_know_what_im_doing)
    # A browser launched elsewhere takes SOCKS5 credentials too.
    attach_socks5_auth(browser)
    context = browser.new_context(**new_context_options(rendered, context_kwargs, proxy))
    context.add_init_script(rendered['init_script'])
    context.camoufox_identity = drawn
    return context
