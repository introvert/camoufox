export interface NewBrowserOptions
	extends Omit<LaunchOptions, "headless">,
		GpuDisplayOptions {
	/** Whether to run the browser headless. On Linux, `"virtual"` runs a real
	 * (non-headless) browser on an Xvfb display instead, and `"virtual-gpu"`
	 * on a headless Xorg server bound to one GPU. */
	headless?: Headless;
	/** A set of launch options generated by `launchOptions()` to use as-is. */
	from_options?: Record<string, any>;
	/** Whether to use a persistent context. */
	persistent_context?: boolean;
	/** Directory for the persistent profile (Playwright's user_data_dir). */
	user_data_dir?: string;
}

/**
 * Launches a Camoufox browser and returns it (Python: `with Camoufox(...) as
 * browser`). Close it with `browser.close()`; a virtual display, if one was
 * spawned, is torn down with it.
 */
export async function Camoufox(
	options: NewBrowserOptions & { persistent_context: true },
): Promise<BrowserContext>;
export async function Camoufox(options?: NewBrowserOptions): Promise<Browser>;
export async function Camoufox(
	options: NewBrowserOptions = {},
): Promise<Browser | BrowserContext> {
	return NewBrowser(firefox, options);
}

/**
 * Launches a new browser instance for Camoufox given a set of launch options.
 *
 * `from_options`: a set of launch options generated by `launchOptions()` to
 * use. `persistent_context`: whether to use a persistent context. Every other
 * option is passed to `launchOptions()`.
 */
export async function NewBrowser(
	playwright: BrowserType,
	options: NewBrowserOptions & { persistent_context: true },
): Promise<BrowserContext>;
export async function NewBrowser(
	playwright: BrowserType,
	options?: NewBrowserOptions,
): Promise<Browser>;
export async function NewBrowser(
	playwright: BrowserType,
	{
		headless,
		from_options,
		persistent_context,
		debug,
		...kwargs
	}: NewBrowserOptions = {},
): Promise<Browser | BrowserContext> {
	const [virtualDisplay, headlessBool] = await startVirtualDisplay(
		headless,
		debug,
		kwargs,
	);

	let fromOptions = from_options;
	// Options the caller built leave its contexts to the caller
	// (hostIdentity).
	let canvasNoise: boolean | undefined = false;
	try {
		if (!fromOptions || !Object.keys(fromOptions).length) {
			canvasNoise = kwargs.canvas_noise ?? undefined;
			// Opt-in (2026-09-17). Pinning keeps the identity's core count by
			// constraining the browser to that many cores; it costs real CPU,
			// needs a launch lock, and does nothing on macOS. Off, the host's own
			// snapped count is reported, so reported and measurable still agree.
			kwargs.pin_cpu_cores ??= false;
			fromOptions = await launchOptions({
				...kwargs,
				headless: headlessBool,
				debug,
			});
		}
		fromOptions = withFirstLaunchTimeout(fromOptions);
	} catch (error) {
		// A failed launch must not leave the display behind.
		virtualDisplay?.kill();
		throw error;
	}

	// Playwright's default viewport deadlocks Juggler when the window is spoofed
	// to a different size (daijro/camoufox#666), so default to no viewport.
	const noViewportDefault = spoofsWindowDimensions(fromOptions);

	// Pin the driver (and so the browser it is about to spawn) to as many cores
	// as the identity reports, so measurable parallelism matches
	// navigator.hardwareConcurrency; the driver gets its cores back afterwards.
	const pinTo = pinnedCoreCount(fromOptions);
	const launch = () =>
		launchWith(
			playwright,
			fromOptions as Record<string, any>,
			Boolean(persistent_context),
			noViewportDefault,
			virtualDisplay,
			canvasNoise,
		);
	try {
		if (!pinTo) {
			return await cpuAffinity.withUnpinnedLaunch(launch);
		}
		const pid = driverPid();
		// The browser inherits the driver's mask at spawn, so two concurrent
		// launches must not interleave pin/restore.
		return await cpuAffinity.withPinLock(async () => {
			const previous = cpuAffinity.pin(pid, pinTo);
			try {
				return await launch();
			} finally {
				cpuAffinity.restore(pid, previous);
			}
		});
	} catch (error) {
		virtualDisplay?.kill();
		throw error;
	}
}

async function launchWith(
	playwright: BrowserType,
	fromOptions: Record<string, any>,
	persistentContext: boolean,
	noViewportDefault: boolean,
	virtualDisplay: VirtualDisplay | null,
	canvasNoise: boolean | undefined,
): Promise<Browser | BrowserContext> {
	// Persistent context. Python passes user_data_dir inside the options; the
	// JS API takes it positionally. A user_data_dir alone also selects it.
	const userDataDir = fromOptions.user_data_dir ?? fromOptions.userDataDir;
	if (persistentContext || userDataDir !== undefined) {
		let options: Record<string, any> = { ...fromOptions };
		delete options.user_data_dir;
		delete options.userDataDir;
		if (
			noViewportDefault &&
			!("viewport" in options || "noViewport" in options)
		) {
			options = applyNoViewport(options);
		} else if ("noViewport" in options) {
			options = applyNoViewport(options);
		}
		// The persistent context is created by the launch itself, so its media
		// features come from these options rather than from newContext().
		for (const [key, value] of Object.entries(STOCK_MEDIA_DEFAULTS)) {
			if (!(key in options)) options[key] = value;
		}
		if (launchesMobile(options) && !("hasTouch" in options)) {
			options.hasTouch = true;
		}
		const context = await playwright.launchPersistentContext(
			userDataDir ?? "",
			options,
		);
		return attachVirtualDisplay(context, virtualDisplay);
	}

	// Browser
	const identity = await hostIdentity(fromOptions, canvasNoise);
	const browser = await playwright.launch(fromOptions);
	if (noViewportDefault) {
		attachNoViewportDefault(browser);
	}
	if (launchesMobile(fromOptions)) {
		attachTouchDefault(browser);
	}
	attachStockMediaDefaults(browser);
	attachDesktopOnlyWarning(browser);
	(browser as any)._camoufoxHostIdentity = identity;
	(browser as any)._camoufoxMachine = launchMachine(fromOptions);
	return attachVirtualDisplay(browser, virtualDisplay);
}

export interface NewContextOptions
	extends Omit<NewIdentityOptions, "locale" | "timezone">,
		Record<string, any> {
	/** Part of the identity, as Playwright names them. */
	locale?: string;
	timezoneId?: string;
}

/** snake_case -> camelCase, as camoufox.server.camel_case does. */
export function camelCase(snake: string): string {
	if (snake.length < 2) return snake;
	const parts = snake.toLowerCase().split("_");
	const joined = parts
		.map((x) => (x ? x[0].toUpperCase() + x.slice(1) : ""))
		.join("");
	return (
		(snake[0] === "_" ? "_" : "") + joined[0].toLowerCase() + joined.slice(1)
	);
}

export interface NewIdentityOptions {
	/** A stored identity to start from. Its values are kept, except the ones
	 * this call sets and what is drawn from them (see `overrides`). */
	identity?: ContextIdentity | null;
	/** A fingerprint preset to draw from. If omitted, fpgen draws. */
	preset?: Record<string, any>;
	/** Target OS for a drawn identity ("windows", "macos", "linux", "android").
	 * On a browser launched without canvas noise, contexts claim the host's OS
	 * and GPU, and another OS or GPU throws ValueError; "android" draws from the
	 * Linux pools, so a Linux host can render it. */
	os?: string;
	/** Firefox major version to claim in the UA. Defaults to the browser's own. */
	ff_version?: string;
	/** BCP-47 tag or language list (Playwright's `locale`). */
	locale?: string;
	/** IANA timezone. */
	timezone?: string;
	/** IPv4 or IPv6 address WebRTC reports. */
	webrtc_ip?: string;
	/** Only read to place the identity where the proxy exits: the WebRTC IP,
	 * timezone and geolocation follow the exit, and a new identity's locale is
	 * drawn for its country, unless given. InvalidIP is thrown if that lookup
	 * fails. It is not stored. */
	proxy?: ProxyConfig;
	geolocation?: { latitude: number; longitude: number; accuracy?: number };
	/** Config keys to set (CONTEXT_IDENTITY_KEYS, and the webGl: and webGl2:
	 * keys). The rest of the identity is drawn to agree: another user agent,
	 * platform or screen draws the fonts, voices and GPU again, from the
	 * identity's own salt, and another GPU brings its own WebGL tables. A key
	 * every context of a browser shares throws ValueError. */
	overrides?: Record<string, any>;
	/** Silences the warnings for overrides and for phone identities. */
	i_know_what_im_doing?: boolean;
}

/**
 * The host identity and machine a browser's contexts must keep. A browser
 * from NewBrowser knows them; one from firefox.connect() is asked once.
 */
export async function browserMachine(
	browser: Browser,
): Promise<[HostIdentity | null, Machine]> {
	const b = browser as any;
	if (!("_camoufoxMachine" in b)) {
		const probe = await browser.newContext();
		let facts: MachineFacts;
		try {
			facts = await (await probe.newPage()).evaluate(MACHINE_PROBE);
		} finally {
			await probe.close();
		}
		[b._camoufoxHostIdentity, b._camoufoxMachine] = machineFromProbe(facts);
	}
	return [b._camoufoxHostIdentity ?? null, b._camoufoxMachine];
}

/**
 * Draws a context identity for `browser`, or changes a stored one, without
 * opening a context. The result is plain JSON: store it, and pass it to
 * NewContext({ identity }) to open a context that is that identity.
 */
export async function NewIdentity(
	browser: Browser,
	{
		identity,
		preset,
		os,
		ff_version,
		locale,
		timezone,
		webrtc_ip,
		proxy,
		geolocation,
		overrides,
		i_know_what_im_doing = false,
	}: NewIdentityOptions = {},
): Promise<ContextIdentity> {
	// Python's fpgen loads its model on import; here it is fetched on first use.
	// launchOptions() awaits it, but a browser from connect() or a custom
	// executable never went through launchOptions().
	await ensureModel();
	const ffVersion = ff_version || browser.version().split(".", 1)[0];
	const [hostIdentity, machine] = await browserMachine(browser);
	let place: {
		webrtcIp?: string;
		geolocation?: NewIdentityOptions["geolocation"];
		timezone?: string;
		locale?: string | null;
	} = { webrtcIp: webrtc_ip, geolocation, timezone, locale };
	if (
		proxy &&
		needsExitGeo(identity, webrtc_ip, geolocation, timezone, locale)
	) {
		place = await placeAtExit(
			await proxyExitGeo(ProxyHelper.asString(proxy)),
			identity,
			webrtc_ip,
			geolocation,
			timezone,
			locale,
		);
	}
	return contextIdentity(hostIdentity, machine, identity, ffVersion, {
		preset: preset as any,
		os,
		locale: place.locale,
		timezone: place.timezone,
		webrtc_ip: place.webrtcIp,
		geolocation: place.geolocation,
		overrides,
		i_know_what_im_doing,
	});
}

/** A context that is `identity`, to store and replay (NewContext sets it). */
export type CamoufoxContext = BrowserContext & {
	camoufoxIdentity: ContextIdentity;
};

/**
 * Creates a new browser context with its own identity: a new one, drawn as a
 * launch draws one, or the stored `identity` (from NewIdentity, or an earlier
 * context's `camoufoxIdentity`). The identity's values are applied through
 * addInitScript, whose setters remove themselves before page scripts run.
 *
 * `locale` and `timezoneId` are part of the identity. The other options are
 * NewIdentity's; `proxy` is also the context's proxy. Every other option goes
 * to Playwright's newContext() and wins over the identity's: pass
 * `storageState` to restore a returning visitor's cookies and storage, and
 * save them with context.storageState().
 */
export async function NewContext(
	browser: Browser,
	{
		identity,
		preset,
		os,
		ff_version,
		webrtc_ip,
		proxy,
		geolocation,
		overrides,
		i_know_what_im_doing = false,
		locale,
		timezoneId,
		...contextOptions
	}: NewContextOptions = {},
): Promise<CamoufoxContext> {
	const ffVersion = ff_version || browser.version().split(".", 1)[0];
	const drawn = await NewIdentity(browser, {
		identity,
		preset,
		os,
		ff_version: ffVersion,
		locale,
		timezone: timezoneId,
		webrtc_ip,
		proxy,
		geolocation,
		overrides,
		i_know_what_im_doing,
	});
	const rendered = renderContextIdentity(
		drawn,
		ffVersion,
		i_know_what_im_doing,
	);
	// The rendered options are already Playwright's JS names (userAgent,
	// deviceScaleFactor, timezoneId); the caller's own options win.
	const opts: Record<string, any> = {
		...rendered.context_options,
		...contextOptions,
	};
	if (proxy) opts.proxy = proxy;
	const context = (await browser.newContext(opts)) as CamoufoxContext;
	await context.addInitScript(rendered.init_script);
	context.camoufoxIdentity = drawn;
	return context;
}
